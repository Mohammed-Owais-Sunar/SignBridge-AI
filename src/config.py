"""Central configuration for SignBridge AI (Phase 3 + Phase 4).

Everything a user may want to change lives HERE, in ONE place:

- the sign class list          -> SIGN_CLASSES
- how many samples to collect  -> SAMPLES_PER_CLASS
- how often a sample is taken  -> SAMPLE_INTERVAL_MS
- where the dataset is stored  -> DATASET_CSV / DATA_DIR
- train/test split settings    -> TEST_SIZE / RANDOM_STATE (Phase 4)
- the Random Forest baseline   -> RANDOM_FOREST_PARAMS (Phase 4)
- where the trained model goes -> TRAINED_MODEL_PATH (Phase 4)

No other module hard-codes the class list or the sample count, so adding a
13th sign later means appending ONE string to SIGN_CLASSES and collecting
samples for it.

IMPORTANT SCOPE NOTE (Phase 3):
This project is a PREDEFINED STATIC HAND-GESTURE RECOGNITION SYSTEM. The
classes below are fixed, predefined gestures. The project does NOT understand
complete sign language, sign-language grammar, or arbitrary continuous sign
language. See README.md "Phase 3".
"""

