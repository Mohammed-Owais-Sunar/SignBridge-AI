# -----------------------------------------------------------------------------
# Phase 4 - training and evaluation (scripts/train_model.py)
# -----------------------------------------------------------------------------
# Reproducible train/test split: 20% of the dataset is held out, stratified
# by class, with a fixed seed. The held-out split is NEVER used for fitting.
TEST_SIZE = 0.20
RANDOM_STATE = 42

# RandomForestClassifier baseline configuration. Deliberately simple - no
