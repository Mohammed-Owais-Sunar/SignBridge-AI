# -----------------------------------------------------------------------------
# Phase 5 - real-time prediction (scripts/predict_realtime.py)
# -----------------------------------------------------------------------------
# CONFIDENCE THRESHOLD: when the Random Forest's best probability for the
# current frame is below this value, the app displays "Uncertain" instead of
# a gesture. 0.50 means the winning class must hold the absolute majority of
# the forest's probability mass (random guessing over 12 classes would be
# ~0.083). Set to 0.0 to always display the raw prediction.
MIN_PREDICTION_CONFIDENCE = 0.50

# MINIMAL ANTI-FLICKER (stability): the displayed label is the majority vote
# over the last PREDICTION_VOTE_WINDOW raw predictions. It only smooths the
# DISPLAY - the classifier itself is untouched, and the raw per-frame
# prediction is always shown on the overlay and printed when it changes.
# Set to 0 to disable voting entirely.
PREDICTION_VOTE_WINDOW = 5

# REAL-TIME PARALLELISM: the forest was TRAINED with n_jobs=-1 (see
# RANDOM_FOREST_PARAMS), but for single-sample prediction the parallel
# dispatch costs far more than it saves (measured on this project:
# ~29.5 ms/query with -1 vs ~7.2 ms/query with 1 - 4.1x faster, with
# BIT-IDENTICAL probabilities). Prediction therefore forces n_jobs=1 on the
# in-memory model at load time. The saved .joblib file is not modified, and
# results are provably unchanged.
#
# NOTE (repair branch): n_jobs only matters for the FALLBACK path now.
# scripts/predict_realtime.predict_proba_single() validates the sample once
# instead of once per tree (scikit-learn re-validates the same row for each
# of the 200 trees: measured 23-27 ms/query -> 5 ms/query, BIT-IDENTICAL
# probabilities; verified by scripts/test_camera_lifecycle.py).
PREDICTION_N_JOBS = 1

# -----------------------------------------------------------------------------
# Webcam source (used by src/camera_worker.py, the Streamlit live feed)
# -----------------------------------------------------------------------------
# CAMERA_INDEX: 0 is the system default camera; raise it (1, 2, ...) when the
# default index belongs to a built-in camera you do not want to use.
# CAMERA_BACKEND: "" = let OpenCV choose (current default, unchanged
# behaviour). On Windows you can pin the backend to "MSMF" or "DSHOW" when
# auto-selection opens the wrong device or probes slowly (measured: auto
# tries FFMPEG first, which cannot open cameras, before succeeding).
CAMERA_INDEX = 0
CAMERA_BACKEND = ""

# -----------------------------------------------------------------------------
# Phase 6 - sentence builder (src/sentence_builder.py)
# -----------------------------------------------------------------------------
# Minimum seconds between two sentence actions (word / SPACE / DELETE). It
# bounds the action rate even if the displayed label ever flaps quickly.
# An action that arrives too soon after the previous one is NOT dropped: it
# stays pending and fires as soon as the cooldown expires while the gesture
# remains visible. 0 disables the time check - the edge-trigger + re-arm
# rules (see src/sentence_builder.py) still apply.
ACTION_COOLDOWN_SECONDS = 0.3

# RE-ARM RULE (when the SAME gesture may trigger again after it already did):
# - hand absent: the display must show "no hand" for this many CONSECUTIVE
#   frames (~0.3 s at 25 fps). A 1-3 frame detection flicker does NOT re-arm,
#   so a held gesture cannot re-fire through a dropped frame, while a
#   deliberate "lower the hand and sign again" re-arms quickly.
# - below-threshold / uncertain display: must persist for this many
#   CONSECUTIVE frames (~0.75 s). Confidence that hovers around
#   MIN_PREDICTION_CONFIDENCE otherwise flaps Gesture <-> Uncertain and
#   would re-fire the same held gesture over and over (observed in live
#   testing before this rule existed: one held gesture produced 5 words).
# A different visible gesture always re-arms IMMEDIATELY (it is its own
# action), and the action cooldown above still bounds the overall rate.
REARM_NO_HAND_FRAMES = 8
REARM_UNCERTAIN_FRAMES = 20
